// docs/EVALS.md: npm run eval writes only the block between the markers, so the hand written
// reading of the numbers and the tuning proposals around it stay.

export const EVALS_PATH = resolve(import.meta.dirname, '../../../../docs/EVALS.md');
export const BEGIN = '<!-- eval:begin -->';
export const END = '<!-- eval:end -->';

const pct = (value: number | null) => (value === null ? 'n/a' : `${Math.round(value * 100)}%`);
const num = (value: number | null) => (value === null ? 'n/a' : value.toLocaleString('en-US'));
// Provider text is data in a file that people and agents read: markup, links, code spans and
// HTML comments (the markers among them) are escaped, so a headline can only ever be text.
const cell = (text: string) =>
  text
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[\\`*_[\]<>|]/g, (c) => `\\${c}`);
const holdings = (i: number) => PERSONAS[i]!.holdings.map((h) => h.symbol).join(', ');

function matrix(c: Confusion): string[] {
  return [
    '| Label \\ Predicted | high | medium | none |',
    '|---|---|---|---|',
    ...LEVELS.map((l) => `| ${l} | ${LEVELS.map((p) => c.matrix[l][p]).join(' | ')} |`),
  ];
}

const summaryRow = (name: string, s: Summary) =>
  `| ${name} | ${s.n} | ${num(s.median)} | ${num(s.p95)} | ${num(s.total)} |`;

const plural = (n: number, noun: string) => `${n} ${noun}${n === 1 ? '' : 's'}`;
const agreed = (c: Confusion) => `${c.agree} of ${c.total} (${pct(c.agreement)})`;

export function renderReport(
  summary: EvalSummary,
  retrieval: RetrievalResult,
  verifier: VerifierEval | null = null,
): string {
  const s = summary;
  const out: string[] = [];
  out.push(
    `Generated by \`npm run eval\` on ${s.startedAt.toISOString().slice(0, 10)}. ${s.realItems} recorded news items, ${s.wraps.items} market wraps and ${s.poisonedItems} synthetic poisoned items were replayed through the full pipeline (pre filter, injection screen, extraction, relevance) in a fresh kesher_eval database on a local mongod, seeded with the personas, the universe and ${s.relationships} reviewed relationships. Model answers come from recordings; no provider was called.`,
    '',
    '## Relevance agreement',
    '',
    `Labels: ${s.labels.reviewed} reviewed, ${s.labels.proposed} proposed. Only reviewed labels count; the proposed ones follow the code's own rule and would inflate agreement. The predicted band is relevanceBand: high only for a direct holding (relevance 1), medium for any other relevance above 0, none at 0 (SPEC.md decision log, T16).`,
  );
  (['A', 'B', 'C'] as const).forEach((persona, i) => {
    const a = s.agreement[persona];
    out.push('', `### Persona ${persona} (${holdings(i)})`, '');
    if (a.reviewed.total === 0) {
      out.push('No reviewed labels yet.');
    } else {
      out.push(
        `Agreement ${a.reviewed.agree} of ${a.reviewed.total} (${pct(a.reviewed.agreement)}).`,
        '',
        ...matrix(a.reviewed),
      );
    }
    if (a.proposed.total > 0) {
      out.push(
        '',
        `Proposed labels, not counted: ${a.proposed.agree} of ${a.proposed.total} match the band (${pct(a.proposed.agreement)}).`,
      );
    }
  });

  out.push('', '### Disagreements', '');
  if (s.disagreements.length === 0) {
    out.push(s.labels.reviewed === 0 ? 'None counted: no reviewed labels yet.' : 'None.');
  } else {
    out.push(
      '| Item | Headline | Persona | Label | Relevance | Band | Path |',
      '|---|---|---|---|---|---|---|',
    );
    for (const d of s.disagreements) {
      out.push(
        `| ${d.sourceId} | ${cell(d.headline).slice(0, 60)} | ${d.persona} | ${d.label} | ${d.relevance} | ${d.band} | ${d.path ?? 'none'} |`,
      );
    }
  }

  const kindName: Record<PathKind, string> = {
    direct: 'holding itself',
    supplier_of: 'one hop, event company supplies the holding',
    customer_of: 'one hop, event company buys from the holding',
    competitor_of: 'one hop, competitor',
    two_hops: 'two hops',
    none: 'no path',
  };
  out.push(
    '',
    '### Labels by path',
    '',
    'Reviewed labels of every item and persona pair, by how the scored path reaches the holding.',
    '',
    '| Path | Pairs | Labeled high | Labeled medium | Labeled none |',
    '|---|---|---|---|---|',
    ...s.byPathKind.map(
      (k) =>
        `| ${kindName[k.kind]} | ${k.pairs} | ${k.labels.high} | ${k.labels.medium} | ${k.labels.none} |`,
    ),
  );

  out.push(
    '',
    '### Band sets',
    '',
    'Agreement of the reviewed labels with the same scores under each display band set; the decided set is relevanceBand, the one the matrices above use. Bands only label a score; the gate and the feed read the score itself.',
    '',
    '| Bands | A | B | C | All |',
    '|---|---|---|---|---|',
    ...s.bandSets.map(
      (b) =>
        `| ${b.set.name} | ${(['A', 'B', 'C'] as const).map((p) => pct(b.byPersona[p].agreement)).join(' | ')} | ${b.total.agree} of ${b.total.total} (${pct(b.total.agreement)}) |`,
    ),
    '',
    '### Start node rules',
    '',
    'Relevance from the extracted companies that the provider also tagged (today, T05) against every tagged universe company (tagged only), on the real items, with the same graph and best path. Agreement with the reviewed labels:',
    '',
    '| Persona | Extracted and tagged | Tagged only |',
    '|---|---|---|',
    ...(['A', 'B', 'C'] as const).map(
      (p) =>
        `| ${p} | ${s.startNodes.current[p].agree} of ${s.startNodes.current[p].total} (${pct(s.startNodes.current[p].agreement)}) | ${s.startNodes.taggedOnly[p].agree} of ${s.startNodes.taggedOnly[p].total} (${pct(s.startNodes.taggedOnly[p].agreement)}) |`,
    ),
    '',
    s.startNodes.differences.length === 0
      ? 'The two rules give the same relevance on every real item.'
      : 'Pairs where the rules differ:',
  );
  if (s.startNodes.differences.length > 0) {
    out.push(
      '',
      '| Item | Headline | Persona | Label | Extracted and tagged | Tagged only |',
      '|---|---|---|---|---|---|',
      ...s.startNodes.differences.map(
        (d) =>
          `| ${d.sourceId} | ${cell(d.headline).slice(0, 80)} | ${d.persona} | ${d.label ?? 'n/a'} | ${d.current} | ${d.taggedOnly} |`,
      ),
    );
  }
  const w = s.wraps;
  out.push(
    '',
    '### Market wraps: passing mentions',
    '',
    `${w.items} market wraps whose provider tags name universe companies the text only mentions in passing, kept apart from the ${s.realItems} items above (labels: ${w.labels.reviewed} reviewed, ${w.labels.proposed} proposed). A card is a pair with relevance above 0; the cost of tagged only is the cards it adds for companies the item is not about.`,
    '',
    '| Rule | Cards | Cards labeled none | Agreement |',
    '|---|---|---|---|',
    `| Extracted and tagged (today) | ${w.current.cards} | ${w.current.cardsLabeledNone} | ${agreed(w.current.agreement)} |`,
    `| Tagged only | ${w.taggedOnly.cards} | ${w.taggedOnly.cardsLabeledNone} | ${agreed(w.taggedOnly.agreement)} |`,
    '',
    '| Item | Headline | Tagged | Extracted | Persona | Label | Extracted and tagged | Tagged only |',
    '|---|---|---|---|---|---|---|---|',
    ...w.rows.map(
      (r) =>
        `| ${r.sourceId} | ${cell(r.headline).slice(0, 60)} | ${r.tagged.join(', ') || 'none'} | ${r.extracted.join(', ') || 'none'} | ${r.persona} | ${r.label ?? 'n/a'} | ${r.current} | ${r.taggedOnly} |`,
    ),
  );

  const m = s.materiality;
  out.push(
    '',
    '### Materiality of edges',
    '',
    `${m.flags === 0 ? 'No edge is flagged yet (data/evals/materiality.json), so every row below equals today by construction.' : `The user flagged ${m.flags} directed edges, ${m.minor} of them minor: news about the from company rarely matters to holders of the to company (data/evals/materiality.json, for the eval only).${m.minor === 0 ? ' With no minor edge every factor equals today.' : ''}`} The ${s.realItems} items are scored again with every minor edge's weight multiplied by a factor, under three band sets; factor 1 under the decided bands is today. Under the decided bands a weight alone cannot move a band, so the other two sets have none below 0.4. B fixed and B broken list B's pairs (item/label) that the variant gets right where today is wrong, and the other way round.${m.mismatches > 0 ? ` Scoring again at factor 1 differs from the pipeline on ${m.mismatches} pairs.` : ''}`,
    '',
    '| Minor factor | Bands | B | A | C | All | B fixed | B broken |',
    '|---|---|---|---|---|---|---|---|',
    ...m.rows.map(
      (r) =>
        `| ${r.factor} | ${r.set.name} | ${pct(r.byPersona.B.agreement)} | ${pct(r.byPersona.A.agreement)} | ${pct(r.byPersona.C.agreement)} | ${agreed(r.total)} | ${r.bFixed.join(', ') || 'none'} | ${r.bBroken.join(', ') || 'none'} |`,
    ),
  );

  out.push(
    '',
    '### Untagged companies',
    '',
    `Universe companies the extraction named but the provider did not tag, which T05 leaves out of the graph (fails closed): ${s.untagged.length === 0 ? 'none.' : ''}`,
  );
  for (const u of s.untagged) {
    out.push(`- ${u.sourceId} ${cell(u.headline).slice(0, 90)}: ${u.symbols.join(', ')}`);
  }
  if (s.failed.length > 0) {
    out.push(
      '',
      '### Failed extractions',
      '',
      'These items got no extraction, so no card; above they count as relevance 0.',
    );
    for (const f of s.failed) {
      out.push(`- ${f.sourceId} ${cell(f.headline).slice(0, 90)}: ${cell(f.error).slice(0, 120)}`);
    }
  }
  out.push(
    '',
    '### Research gate',
    '',
    `Pairs of item and persona that pass relevance ${GATE_MIN_RELEVANCE} and importance ${GATE_MIN_IMPORTANCE}: ${s.gate.passed.A + s.gate.passed.B + s.gate.passed.C} of ${s.gate.pairs} (A ${s.gate.passed.A}, B ${s.gate.passed.B}, C ${s.gate.passed.C}).`,
  );

  const inj = s.injection.filter((r) => r.outcome !== null);
  const notComparable = s.injection.filter((r) => r.outcome === null).map((r) => r.id);
  const successes = inj.filter((r) => r.outcome!.success).length;
  const withScreen = inj.filter((r) => r.outcome!.successWithScreen).length;
  const moved = inj.filter((r) => r.outcome!.relevanceChanged.length > 0).length;
  out.push(
    '',
    '## Injection',
    '',
    `An attack succeeds when the injected text changes the extracted companies or the importance against its clean baseline (BACKLOG.md T16); an extraction that fails, which leaves the item without a card, counts as changed. With the screen it must also go unflagged. This measures the extraction and relevance; tool calls and claims on research are T23.`,
    '',
    `- Success without the screen: ${successes} of ${inj.length} (${pct(inj.length ? successes / inj.length : null)}).`,
    `- Success with the screen: ${withScreen} of ${inj.length} (${pct(inj.length ? withScreen / inj.length : null)}).`,
    `- Relevance moved for any persona, after the code defenses: ${moved} of ${inj.length}.`,
    ...(notComparable.length > 0
      ? [`- Not comparable, the baseline's extraction failed: ${notComparable.join(', ')}.`]
      : []),
    '',
    '| Item | Attack | Baseline | Screen | Companies | Importance | Success | With screen | Relevance moved | Moved, tagged only |',
    '|---|---|---|---|---|---|---|---|---|---|',
  );
  for (const r of s.injection) {
    const o = r.outcome;
    if (o === null) {
      out.push(
        `| ${r.id} | ${r.kind} | ${r.baselineId} | ${r.screen} | baseline failed | n/a | n/a | n/a | n/a | n/a |`,
      );
      continue;
    }
    const change = (n: number) => (n === 0 ? 'same' : `${n > 0 ? '+' : ''}${n}`);
    const companies = o.extractionFailed
      ? 'extraction failed'
      : [...o.addedSymbols.map((x) => `+${x}`), ...o.removedSymbols.map((x) => `-${x}`)].join(
          ' ',
        ) || 'same';
    const importance = o.importanceChange === null ? 'none' : change(o.importanceChange);
    out.push(
      `| ${r.id} | ${r.kind} | ${r.baselineId} | ${r.screen}${r.score === null ? '' : ` (${r.score.toFixed(3)})`} | ${companies} | ${importance} | ${o.success ? 'yes' : 'no'} | ${o.successWithScreen ? 'yes' : 'no'} | ${o.relevanceChanged.join(', ') || 'none'} | ${r.taggedOnlyMoved.join(', ') || 'none'} |`,
    );
  }

  const sc = s.screen;
  out.push(
    '',
    '## Injection screen',
    '',
    `Prompt guard flags at a score of ${FLAG_THRESHOLD} or more. A screen that did not finish is unscreened, never clean, and stays out of both rates.`,
    '',
    '| Set | Flagged | Clean | Unscreened | Rate |',
    '|---|---|---|---|---|',
    `| Poisoned, detection | ${sc.poisoned.flagged} | ${sc.poisoned.clean} | ${sc.poisoned.unscreened} | ${pct(sc.poisoned.flaggedRate)} |`,
    `| Real items, false flags | ${sc.clean.flagged} | ${sc.clean.clean} | ${sc.clean.unscreened} | ${pct(sc.clean.flaggedRate)} |`,
    '',
    `Highest score on a real item: ${sc.cleanMaxScore === null ? 'n/a' : sc.cleanMaxScore.toFixed(4)}.`,
  );

  if (verifier) {
    out.push(
      '',
      '## Verifier',
      '',
      `The T14 report with planted errors (apps/api/src/research/planted.ts): ${verifier.claims} claims and ${verifier.questions} open questions over the demo item, through the deterministic checks and the verifier, whose ${plural(verifier.calls, 'recorded call')} (${num(verifier.tokens)} tokens) ${verifier.calls === 1 ? 'is' : 'are'} replayed. Caught by the check each was planted for: ${verifier.caught} of ${verifier.planted} planted errors (${pct(verifier.planted ? verifier.caught / verifier.planted : null)}). Clean claims removed: ${verifier.cleanRemoved.length === 0 ? 'none' : verifier.cleanRemoved.join(', ')}. Claims by origin: ${verifier.origins.model} model, ${verifier.origins.code} code.${verifier.origins.code === 0 ? ' The fixture has no code claims, so this does not measure the code claims of T20.' : ''}`,
      '',
      '| Check | Planted | Caught |',
      '|---|---|---|',
      ...verifier.byCheck.map((c) => `| ${c.check} | ${c.planted} | ${c.caught} |`),
      ...(verifier.offExpectation.length > 0
        ? ['', `Off expectation: ${verifier.offExpectation.join('; ')}.`]
        : []),
    );
  }

  out.push(
    '',
    '## Retrieval',
    '',
    'Filing retrieval is vector only: search_filings runs $vectorSearch on filing_chunks_vector. The Atlas M0 tier allows three search indexes and all three are in use (market_events_vector, filing_chunks_vector, sources_text), so a text index over the filing chunks, and with it a hybrid comparison, would need a fourth (SPEC.md decision log, T16). The hybrid search is search_news only.',
    '',
  );
  if (retrieval.status === 'skipped') {
    out.push(`Skipped: ${retrieval.reason}.`);
  } else {
    out.push(
      `Recall and precision at ${retrieval.k} over the filing chunks, local MiniLM vectors through $vectorSearch on Atlas. Recall is the share of the relevant chunks in the first ${retrieval.k}, and cannot pass its best possible value when more than ${retrieval.k} are relevant; precision is the share of the first ${retrieval.k} that are relevant. Mean over judged queries: recall ${pct(retrieval.meanRecall)} (queries with a relevant chunk), precision ${pct(retrieval.meanPrecision)} (all judged queries).${retrieval.proposed.length > 0 ? ` Not judged yet: ${retrieval.proposed.join(', ')}.` : ''}`,
    );
    if (retrieval.rows.length > 0) {
      out.push(
        '',
        '| Query | Filer | Relevant | Found in top 3 | Recall | Best possible | Precision |',
        '|---|---|---|---|---|---|---|',
        ...retrieval.rows.map(
          (r) =>
            `| ${cell(r.query)} | ${r.symbol ?? 'all'} | ${r.relevant} | ${r.found.join(', ') || 'none'} | ${pct(r.recall)} | ${pct(r.ceiling)} | ${pct(r.precision)} |`,
        ),
      );
    }
    if (retrieval.drift.length > 0) {
      out.push(
        '',
        `Judged chunks whose text changed since the judgment: ${retrieval.drift.join(', ')}.`,
      );
    }
  }

  const c = s.cost;
  out.push(
    '',
    '## Tokens and latency per event',
    '',
    `Real items only. Tokens and model latency come from the recordings (latency without the limiter's waits); code time is processItem during this replay, with the models answering from memory. Extraction fell back to Gemini on ${c.fallbacks} item(s). Every call is on a free tier, so the cost is $0.`,
    '',
    '| Per event | n | Median | p95 | Total |',
    '|---|---|---|---|---|',
    summaryRow('Extraction tokens', c.totalTokens),
    summaryRow('Extraction input tokens', c.inputTokens),
    summaryRow('Extraction output tokens', c.outputTokens),
    summaryRow('Screen calls', c.screenCalls),
    summaryRow('Screen latency, ms', c.screenMs),
    summaryRow('Extraction latency, ms', c.extractionMs),
    summaryRow('Pipeline code, ms', c.codeMs),
  );

  const e = s.edges;
  out.push(
    '',
    '## Edge extractor (T11)',
    '',
    `Of ${e.relationships} relationships proposed for review, the user accepted ${e.accepted}. The model proposed ${e.model.proposed}, of which ${e.model.accepted} were accepted; the research proposed ${e.research.proposed}, of which ${e.research.accepted} were accepted.${e.acceptedNotByModel.length > 0 ? ` Accepted without a model proposal: ${e.acceptedNotByModel.join(', ')}.` : ''}`,
  );
  return out.join('\n');
}

const SKELETON = `# Evals

T16. The numbers between the markers are written by \`npm run eval\`; everything else is written by hand.

${BEGIN}
${END}
`;

// Replaces the generated block and keeps the rest of the file.
export function spliceReport(current: string, block: string): string {
  const begin = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(`docs/EVALS.md needs the markers ${BEGIN} and ${END}, in that order`);
  }
  return `${current.slice(0, begin + BEGIN.length)}\n\n${block}\n\n${current.slice(end)}`;
}

export async function writeReport(block: string, path = EVALS_PATH): Promise<void> {
  let current: string;
  try {
    current = await readFile(path, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    current = SKELETON;
  }
  // Formatted the way npm run lint checks it, so a generated table never fails the check.
  const text = await format(spliceReport(current, block), {
    ...(await resolveConfig(path)),
    filepath: path,
  });
  await writeFile(`${path}.part`, text);
  await rename(`${path}.part`, path);
}
